#!/usr/bin/env python3
"""Generate evals/activation-summary.md from every evals/<skill>/activation-results.json.

The file lists, per skill, recall on the should_load requests (how many the skill was picked for) and the false-pick
rate on the should_not_load requests (how many the skill was wrongly picked for), which skills the missed and
should-not requests went to, and a flagged list: skills picked on fewer than 4 of their 6 should_load requests or with
any false pick. The list is information only; the check never changes a description. With --check nothing is written;
the exit code is 1 when the file does not match the results (CI uses this).
"""
import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import activation as act  # noqa: E402
import validate_evals  # noqa: E402
from roots import LIVE_ROOTS, skill_dirs  # noqa: E402

OUT = Path("evals") / "activation-summary.md"
INTRO = (
    "This is a routing check from descriptions only. A model is shown the name and description of every skill (what an "
    "agent sees before it loads anything) and one request, and says which single skill, if any, it would load. It does "
    "not show that a skill is good, and it is not the loaded rate of the held-out runs, which stays the evidence for "
    "whether the model uses a skill in a real task. No description was changed because of it. Requests are in "
    "`evals/<skill>/activation.json` and per-request picks in `evals/<skill>/activation-results.json`; "
    "regenerate with `python3 scripts/activation_summary.py`."
)


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def went_to(picks, own=None):
    """'name 2, none 1' for a list of picks; the skill's own name is shown as itself."""
    counts = Counter("none" if p is None else ("itself" if p == own else p) for p in picks)
    return ", ".join(f"{k} {v}" for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))) or "-"


def collect(root):
    """[(skill, results or None)] for the live skills, design skills first."""
    return [(d.name, act.load_json(Path(root) / "evals" / d.name / "activation-results.json"))
            for _, d in skill_dirs(root, LIVE_ROOTS)]


def pct(n, total):
    return f"{100 * n / total:.0f}%" if total else "-"


def render(root):
    rows = collect(root)
    done = [(s, r) for s, r in rows if isinstance(r, dict)]
    lines = ["# Activation summary", "",
             "<!-- Generated by scripts/activation_summary.py from evals/*/activation-results.json. Do not edit by hand. -->",
             "", INTRO, ""]
    if not done:
        return lines + ["No activation results yet."]
    hit = sum(r["should_load"]["picked"] for _, r in done)
    total = sum(r["should_load"]["total"] for _, r in done)
    wrong = sum(r["should_not_load"]["false_picks"] for _, r in done)
    not_total = sum(r["should_not_load"]["total"] for _, r in done)
    models = sorted({r["model"] + (f" ({r['model_id']})" if r.get("model_id") else "") for _, r in done})
    dates = sorted({r["date"] for _, r in done})
    lines += [f"**Overall:** recall {hit} of {total} ({pct(hit, total)}); false-pick rate {wrong} of {not_total} "
              f"({pct(wrong, not_total)}) across {len(done)} skills. Model: {', '.join(models)}; run "
              f"{dates[0] if len(dates) == 1 else dates[0] + ' to ' + dates[-1]}.", ""]
    flagged = sorted(((s, r, act.flagged(r)) for s, r in done if act.flagged(r)),
                     key=lambda x: (x[1]["should_load"]["picked"], -x[1]["should_not_load"]["false_picks"], x[0]))
    lines += ["## Flagged", "",
              f"Skills picked on fewer than {act.LOW_RECALL} of their {act.SHOULD_LOAD} should_load requests, or with any "
              "false pick. Information for after the first release; the descriptions are unchanged.", ""]
    if flagged:
        lines += ["| Skill | Recall | False picks | Why | Missed requests went to |", "|---|---|---|---|---|"]
        for s, r, why in flagged:
            sl, sn = r["should_load"], r["should_not_load"]
            miss = went_to([x["picked"] for x in sl["results"] if not x["correct"]])
            lines.append(f"| {s} | {sl['picked']} of {sl['total']} | {sn['false_picks']} of {sn['total']} | "
                         f"{cell('; '.join(why))} | {cell(miss)} |")
    else:
        lines.append("No skill is flagged.")
    lines += ["", "## All skills", "",
              "| Skill | Recall | False picks | Missed requests went to | Should-not requests went to |",
              "|---|---|---|---|---|"]
    for s, r in rows:
        if not isinstance(r, dict):
            lines.append(f"| {s} | not run | not run | - | - |")
            continue
        sl, sn = r["should_load"], r["should_not_load"]
        miss = went_to([x["picked"] for x in sl["results"] if not x["correct"]])
        elsewhere = went_to([x["picked"] for x in sn["results"]], own=s)
        lines.append(f"| {s} | {sl['picked']} of {sl['total']} | {sn['false_picks']} of {sn['total']} | "
                     f"{cell(miss)} | {cell(elsewhere)} |")
    return lines


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    p.add_argument("--check", action="store_true", help="exit 1 if evals/activation-summary.md differs from the results")
    args = p.parse_args(argv)
    path = Path(args.root) / OUT
    if args.check:
        problems = validate_evals.activation_coverage(Path(args.root) / "evals", validate_evals.activation_context(args.root))
        if problems:
            print("\n".join(problems), file=sys.stderr)
            return 1
    new = "\n".join(render(args.root)) + "\n"
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    if new == current:
        print("evals/activation-summary.md is up to date")
        return 0
    if args.check:
        print("evals/activation-summary.md is out of date; run: python3 scripts/activation_summary.py")
        return 1
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new, encoding="utf-8")
    print("evals/activation-summary.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
